class DebugPanel extends StatefulWidget {
  const DebugPanel({super.key});
  @override
  State<DebugPanel> createState() => _DebugPanelState();
}

class _DebugPanelState extends State<DebugPanel> {
  @override
  Widget build(BuildContext context) {
    return Card(
      margin: const EdgeInsets.only(top: 24),
      child: Padding(
        padding: const EdgeInsets.all(12),
        child: Column(crossAxisAlignment: CrossAxisAlignment.start, children: [
          const Text('DEBUG: injected faults (development only)',
              style: TextStyle(fontWeight: FontWeight.bold)),
          SwitchListTile(
              title: const Text('Hide ack after real commit (T09)'),
              value: attemptRepo.injectLostAck,
              onChanged: (v) => setState(() => attemptRepo.injectLostAck = v)),
          Row(children: [
            const Text('Cloud error: '),
            DropdownButton<String?>(
              value: attemptRepo.injectErrorCode,
              items: const [
                DropdownMenuItem(value: null, child: Text('none')),
                DropdownMenuItem(value: 'unavailable', child: Text('unavailable')),
                DropdownMenuItem(value: 'resource-exhausted', child: Text('resource-exhausted')),
              ],
              onChanged: (v) => setState(() => attemptRepo.injectErrorCode = v),
            ),
          ]),
          Row(children: [
            const Text('API fault: '),
            DropdownButton<ApiFault>(
              value: triviaApi.fault,
              items: [
                for (final f in ApiFault.values) DropdownMenuItem(value: f, child: Text(f.name)),
              ],
              onChanged: (v) => setState(() => triviaApi.fault = v ?? ApiFault.none),
            ),
          ]),
        ]),
      ),
    );
  }
}
