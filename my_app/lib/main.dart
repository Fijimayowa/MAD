class App extends StatelessWidget {
  const App({super.key});
  @override
  Widget build(BuildContext context) => MaterialApp(
        title: 'GK Cloud Round',
        theme: ThemeData(colorSchemeSeed: Colors.indigo, useMaterial3: true),
        home: const AuthGate(),
      );
}

/// Shared services (one instance each so debug fault flags persist).
final triviaApi = TriviaApi();
final attemptRepo = AttemptRepository();

class AuthGate extends StatelessWidget {
  const AuthGate({super.key});
  @override
  Widget build(BuildContext context) {
    return StreamBuilder<User?>(
      stream: FirebaseAuth.instance.authStateChanges(),
      builder: (context, snap) {
        if (snap.connectionState == ConnectionState.waiting) {
          return const Scaffold(body: Center(child: CircularProgressIndicator()));
        }
        final user = snap.data;
        if (user == null) return const SignInPage(); // signedOut
        // A new controller per UID, so an old user's responses never reach a new user.
        return HomePage(key: ValueKey(user.uid), uid: user.uid, email: user.email ?? '');
      },
    );
  }
}

// ---------------- Sign in ----------------

class SignInPage extends StatefulWidget {
  const SignInPage({super.key});
  @override
  State<SignInPage> createState() => _SignInPageState();
}

class _SignInPageState extends State<SignInPage> {
  final _email = TextEditingController();
  final _password = TextEditingController();
  String? _error; // authError
  bool _busy = false;

  Future<void> _signIn() async {
    setState(() {
      _busy = true;
      _error = null;
    });
    try {
      await FirebaseAuth.instance.signInWithEmailAndPassword(
          email: _email.text.trim(), password: _password.text);
    } on FirebaseAuthException catch (e) {
      // Never log the password.
      setState(() => _error = switch (e.code) {
            'invalid-credential' || 'wrong-password' || 'user-not-found' =>
              'Email or password is incorrect.',
            'invalid-email' => 'That email address is not valid.',
            'network-request-failed' => 'No network. Check your connection.',
            'too-many-requests' => 'Too many attempts. Wait a bit and try again.',
            _ => 'Sign-in failed (${e.code}).',
          });
    } finally {
      if (mounted) setState(() => _busy = false);
    }
  }

  @override
  Widget build(BuildContext context) {
    return Scaffold(
      appBar: AppBar(title: const Text('Sign in')),
      body: Padding(
        padding: const EdgeInsets.all(24),
        child: Column(children: [
          TextField(
              controller: _email,
              keyboardType: TextInputType.emailAddress,
              decoration: const InputDecoration(labelText: 'Email')),
          TextField(
              controller: _password,
              obscureText: true,
              decoration: const InputDecoration(labelText: 'Password')),
          const SizedBox(height: 16),
          if (_error != null)
            Row(children: [
              const Icon(Icons.error_outline, color: Colors.red),
              const SizedBox(width: 8),
              Expanded(child: Text(_error!, style: const TextStyle(color: Colors.red))),
            ]),
          const SizedBox(height: 16),
          FilledButton(
              onPressed: _busy ? null : _signIn,
              child: _busy
                  ? const SizedBox(
                      height: 18, width: 18, child: CircularProgressIndicator(strokeWidth: 2))
                  : const Text('Sign in')),
        ]),
      ),
    );
  }
}

// ---------------- Home ----------------

class HomePage extends StatefulWidget {
  const HomePage({super.key, required this.uid, required this.email});
  final String uid;
  final String email;
  @override
  State<HomePage> createState() => _HomePageState();
}

class _HomePageState extends State<HomePage> {
  late final QuizController c =
      QuizController(api: triviaApi, repo: attemptRepo, uid: widget.uid);
  final _idField = TextEditingController();
  String? _retrieveMsg;
  SavedAttempt? _retrieved;

  @override
  void initState() {
    super.initState();
    c.addListener(() => setState(() {}));
  }

  @override
  void dispose() {
    c.dispose();
    super.dispose();
  }

  Future<void> _retrieve() async {
    setState(() {
      _retrieveMsg = 'Reading from server…';
      _retrieved = null;
    });
    try {
      final s = await retrieveAttempt(attemptRepo, widget.uid, _idField.text);
      setState(() {
        _retrieved = s;
        _retrieveMsg = null;
      });
    } catch (e) {
      setState(() => _retrieveMsg = '$e');
    }
  }

  @override
  Widget build(BuildContext context) {
    final inRound = c.phase != Phase.idle;
    return Scaffold(
      appBar: AppBar(
        title: const Text('General Knowledge'),
        actions: [
          Tooltip(
            message: c.unresolved ? 'Finish or resolve the save first' : 'Sign out',
            child: IconButton(
              icon: const Icon(Icons.logout),
              onPressed: c.unresolved ? null : () => FirebaseAuth.instance.signOut(),
            ),
          ),
        ],
      ),
      body: ListView(padding: const EdgeInsets.all(16), children: [
        Text('Signed in as ${widget.email}', style: Theme.of(context).textTheme.bodySmall),
        const SizedBox(height: 12),
        if (!inRound) ...[
          FilledButton(onPressed: c.startRound, child: const Text('Start round')),
          const SizedBox(height: 24),
          const Text('Retrieve a saved attempt by round ID'),
          TextField(
              controller: _idField,
              decoration: const InputDecoration(labelText: 'Round ID')),
          const SizedBox(height: 8),
          OutlinedButton(onPressed: _retrieve, child: const Text('Read from server')),
          if (_retrieveMsg != null) Padding(padding: const EdgeInsets.all(8), child: Text(_retrieveMsg!)),
          if (_retrieved != null) _SavedCard(_retrieved!),
          if (kDebugMode) const DebugPanel(),
        ] else
          RoundView(c: c),
      ]),
    );
  }
}

class _SavedCard extends StatelessWidget {
  const _SavedCard(this.s);
  final SavedAttempt s;
  @override
  Widget build(BuildContext context) => Card(
        child: Padding(
          padding: const EdgeInsets.all(12),
          child: Column(crossAxisAlignment: CrossAxisAlignment.start, children: [
            const Row(children: [
              Icon(Icons.cloud_done, color: Colors.green),
              SizedBox(width: 8),
              Text('Cloud verified', style: TextStyle(fontWeight: FontWeight.bold)),
            ]),
            Text('Path: ${s.path}'),
            Text('Score: ${s.data['correctCount']} / ${s.data['questionCount']}'),
            Text('submittedAt: ${s.submittedAt.toIso8601String()}'),
            Text('Fields: ${s.data.keys.join(', ')}'),
          ]),
        ),
      );
}

// ---------------- Round ----------------

class RoundView extends StatelessWidget {
  const RoundView({super.key, required this.c});
  final QuizController c;

  @override
  Widget build(BuildContext context) {
    switch (c.phase) {
      case Phase.loading:
        return const Padding(
          padding: EdgeInsets.all(32),
          child: Column(children: [
            CircularProgressIndicator(),
            SizedBox(height: 12),
            Text('Loading questions…'),
          ]),
        );
      case Phase.requestError:
        return _Banner(
          icon: Icons.wifi_off,
          color: Colors.red,
          text: c.message,
          action: FilledButton(onPressed: c.startRound, child: const Text('Retry')),
        );
      case Phase.playing:
        return _QuestionView(c: c);
      default:
        return _ReviewView(c: c);
    }
  }
}

class _QuestionView extends StatelessWidget {
  const _QuestionView({required this.c});
  final QuizController c;
  @override
  Widget build(BuildContext context) {
    final q = c.questions[c.index];
    final sel = c.selections[c.index];
    return Column(crossAxisAlignment: CrossAxisAlignment.stretch, children: [
      LinearProgressIndicator(value: (c.index + 1) / 10),
      const SizedBox(height: 8),
      Text('Question ${c.index + 1} of 10'),
      const SizedBox(height: 12),
      Text(q.text, style: Theme.of(context).textTheme.titleMedium),
      const SizedBox(height: 12),
      for (var i = 0; i < q.choices.length; i++) _choice(q, i, sel),
      if (sel != null) ...[
        const SizedBox(height: 8),
        Row(children: [
          Icon(q.choices[sel] == q.correct ? Icons.check_circle : Icons.cancel,
              color: q.choices[sel] == q.correct ? Colors.green : Colors.red),
          const SizedBox(width: 8),
          Expanded(
              child: Text(q.choices[sel] == q.correct
                  ? 'Correct!'
                  : 'Not quite. Correct answer: ${q.correct}')),
        ]),
        const SizedBox(height: 8),
        FilledButton(
            onPressed: c.next,
            child: Text(c.index == 9 ? 'Finish' : 'Next')),
      ],
    ]);
  }

  Widget _choice(Question q, int i, int? sel) {
    Color? bg;
    IconData? icon;
    if (sel != null) {
      if (q.choices[i] == q.correct) {
        bg = Colors.green.shade100;
        icon = Icons.check;
      } else if (i == sel) {
        bg = Colors.red.shade100;
        icon = Icons.close;
      }
    }
    return Card(
      color: bg,
      child: ListTile(
        title: Text(q.choices[i]),
        trailing: icon == null ? null : Icon(icon),
        onTap: sel == null ? () => c.select(i) : null, // disabled once answered
      ),
    );
  }
}

class _ReviewView extends StatelessWidget {
  const _ReviewView({required this.c});
  final QuizController c;

  @override
  Widget build(BuildContext context) {
    final p = c.phase;
    final canSubmit = p == Phase.readyToSubmit || p == Phase.saveFailed;
    return Column(crossAxisAlignment: CrossAxisAlignment.stretch, children: [
      Text('Final score: ${c.correctCount} / 10',
          style: Theme.of(context).textTheme.headlineSmall),
      const SizedBox(height: 8),
      _status(context),
      const SizedBox(height: 8),
      Row(children: [
        Expanded(
            child: FilledButton(
                onPressed: canSubmit ? c.submit : null,
                child: Text(p == Phase.saveFailed ? 'Retry save (same round)' : 'Submit'))),
        const SizedBox(width: 8),
        Expanded(
            child: OutlinedButton(
                onPressed: c.canReplay ? c.startRound : null,
                child: const Text('Replay'))),
      ]),
      const Divider(height: 24),
      for (var i = 0; i < c.questions.length; i++) _reviewTile(i),
    ]);
  }

  Widget _status(BuildContext context) {
    switch (c.phase) {
      case Phase.submitting:
      case Phase.verifying:
        return Row(children: [
          const SizedBox(height: 18, width: 18, child: CircularProgressIndicator(strokeWidth: 2)),
          const SizedBox(width: 8),
          Text(c.message),
        ]);
      case Phase.cloudVerified:
        return Column(crossAxisAlignment: CrossAxisAlignment.start, children: [
          const Row(children: [
            Icon(Icons.cloud_done, color: Colors.green),
            SizedBox(width: 8),
            Text('Cloud verified', style: TextStyle(fontWeight: FontWeight.bold)),
          ]),
          if (c.verified != null) ...[
            Text('Path: ${c.verified!.path}'),
            Text('submittedAt: ${c.verified!.submittedAt.toIso8601String()}'),
          ],
        ]);
      case Phase.saveUnknown:
      case Phase.verificationUnavailable:
        return _Banner(
            icon: Icons.help_outline,
            color: Colors.orange,
            text: c.message,
            action: FilledButton(onPressed: c.checkServer, child: const Text('Check server')));
      case Phase.permissionDenied:
        return _Banner(icon: Icons.lock, color: Colors.red, text: c.message);
      case Phase.saveFailed:
        return _Banner(icon: Icons.cloud_off, color: Colors.red, text: c.message);
      default:
        return const SizedBox.shrink();
    }
  }

  Widget _reviewTile(int i) {
    final q = c.questions[i];
    final s = c.selections[i];
    final ok = s != null && q.choices[s] == q.correct;
    return ListTile(
      leading: Icon(ok ? Icons.check_circle : Icons.cancel, color: ok ? Colors.green : Colors.red),
      title: Text('${i + 1}. ${q.text}'),
      subtitle: Text('Your answer: ${s == null ? "—" : q.choices[s]}\nCorrect: ${q.correct}'),
      isThreeLine: true,
    );
  }
}

class _Banner extends StatelessWidget {
  const _Banner({required this.icon, required this.color, required this.text, this.action});
  final IconData icon;
  final Color color;
  final String text;
  final Widget? action;
  @override
  Widget build(BuildContext context) => Card(
        color: color.withOpacity(0.1),
        child: Padding(
          padding: const EdgeInsets.all(12),
          child: Column(crossAxisAlignment: CrossAxisAlignment.start, children: [
            Row(children: [
              Icon(icon, color: color),
              const SizedBox(width: 8),
              Expanded(child: Text(text)),
            ]),
            if (action != null) ...[const SizedBox(height: 8), action!],
          ]),
        ),
      );
}

